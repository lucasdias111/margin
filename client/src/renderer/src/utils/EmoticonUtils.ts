const EMOTICONS: [RegExp, string][] = [
  [/(?<!\w):-?\)(?!\w)/g, '😊'],
  [/(?<!\w):-?D(?!\w)/g, '😄'],
  [/(?<!\w)=\)(?!\w)/g, '😊'],
  [/(?<!\w)=D(?!\w)/g, '😄'],
  [/(?<!\w)xD(?!\w)/gi, '😆'],
  [/(?<!\w):'\)(?!\w)/g, '😂'],
  [/(?<!\w)\^_?\^(?!\w)/g, '😊'],
  [/(?<!\w)\^-?\^(?!\w)/g, '😊'],

  [/(?<!\w):-?\((?!\w)/g, '😢'],
  [/(?<!\w)=\((?!\w)/g, '😢'],
  [/(?<!\w):'\((?!\w)/g, '😭'],
  [/(?<!\w):-?\[(?!\w)/g, '😞'],

  [/(?<!\w);-?\)(?!\w)/g, '😉'],
  [/(?<!\w);-?D(?!\w)/g, '😄'],
  [/(?<!\w)\*-?\)(?!\w)/g, '😉'],

  [/(?<!\w):-?P(?!\w)/gi, '😛'],
  [/(?<!\w);-?P(?!\w)/gi, '😜'],
  [/(?<!\w)=-?P(?!\w)/gi, '😛'],
  [/(?<!\w)xP(?!\w)/gi, '😝'],

  [/(?<!\w):-?\|(?!\w)/g, '😐'],
  [/(?<!\w)=-?\|(?!\w)/g, '😐'],
  [/(?<!\w):-\/(?!\w)/g, '😕'],
  [/(?<!\w):-\\(?!\w)/g, '😕'],

  [/(?<!\w):-?O(?!\w)/gi, '😮'],
  [/(?<!\w):-?o(?!\w)/g, '😮'],
  [/(?<!\w)=O(?!\w)/gi, '😮'],
  [/(?<!\w):-?0(?!\w)/g, '😮'],

  [/(?<!\w)<3(?!\w)/g, '❤️'],
  [/(?<!\w)<\/3(?!\w)/g, '💔'],

  [/(?<!\w)>:-?\((?!\w)/g, '😠'],
  [/(?<!\w)>:-?\)(?!\w)/g, '😈'],
  [/(?<!\w)>:O(?!\w)/gi, '😡'],

  [/(?<!\w)B-?\)(?!\w)/g, '😎'],
  [/(?<!\w)8-?\)(?!\w)/g, '😎'],

  [/(?<!\w):-S(?!\w)/gi, '😅'],
  [/(?<!\w):-s(?!\w)/g, '😅'],
  [/(?<!\w)\^\^'(?!\w)/g, '😅'],

  [/(?<!\w):-\*(?!\w)/g, '😘'],
  [/(?<!\w)=\*(?!\w)/g, '😘'],
  [/(?<!\w):x(?!\w)/gi, '😘'],

  [/(?<!\w)\|-?\)(?!\w)/g, '😴'],
  [/(?<!\w)x-?\)(?!\w)/g, '😵'],
  [/(?<!\w)x-?\((?!\w)/g, '😵'],
  [/(?<!\w)%-?\)(?!\w)/g, '😵'],

  [/(?<!\w):-#(?!\w)/g, '🤐'],
  [/(?<!\w):-&(?!\w)/g, '🤢'],
  [/(?<!\w)\(y\)(?!\w)/gi, '👍'],
  [/(?<!\w)\(n\)(?!\w)/gi, '👎'],
  [/(?<!\w)\(ok\)(?!\w)/gi, '👌'],
  [/(?<!\w)\(clap\)(?!\w)/gi, '👏'],
  [/(?<!\w)\(wave\)(?!\w)/gi, '👋'],
  [/(?<!\w)\(fire\)(?!\w)/gi, '🔥'],
  [/(?<!\w)\(100\)(?!\w)/g, '💯'],
  [/(?<!\w)\(star\)(?!\w)/gi, '⭐']
]

export function replaceEmoticons(text: string): string {
  return EMOTICONS.reduce((acc, [pattern, emoji]) => acc.replace(pattern, emoji), text)
}
