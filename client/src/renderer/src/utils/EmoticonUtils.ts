const EMOTICONS: [RegExp, string][] = [
  [/:-?\)/g, '😊'],
  [/:-?D/g, '😄'],
  [/=\)/g, '😊'],
  [/=D/g, '😄'],
  [/xD/gi, '😆'],
  [/:'\)/g, '😂'],
  [/\^_?\^/g, '😊'],
  [/\^-?\^/g, '😊'],

  [/:-?\(/g, '😢'],
  [/=\(/g, '😢'],
  [/:'\(/g, '😭'],
  [/:-?\[/g, '😞'],

  [/;-?\)/g, '😉'],
  [/;-?D/g, '😄'],
  [/\*-?\)/g, '😉'],

  [/:-?P/gi, '😛'],
  [/;-?P/gi, '😜'],
  [/=-?P/gi, '😛'],
  [/xP/gi, '😝'],

  [/:-?\|/g, '😐'],
  [/=-?\|/g, '😐'],
  [/:-\//g, '😕'],
  [/:-\\/g, '😕'],

  [/:-?O/gi, '😮'],
  [/:-?o/g, '😮'],
  [/=O/gi, '😮'],
  [/:-?0/g, '😮'],

  [/<3/g, '❤️'],
  [/<\/3/g, '💔'],

  [/>:-?\(/g, '😠'],
  [/>:-?\)/g, '😈'],
  [/>:O/gi, '😡'],

  [/B-?\)/g, '😎'],
  [/8-?\)/g, '😎'],

  [/:-S/gi, '😅'],
  [/:-s/g, '😅'],
  [/\^\^'/g, '😅'],

  [/:-\*/g, '😘'],
  [/=\*/g, '😘'],
  [/:x/gi, '😘'],

  [/\|-?\)/g, '😴'],
  [/x-?\)/g, '😵'],
  [/x-?\(/g, '😵'],
  [/%-?\)/g, '😵'],

  [/:-#/g, '🤐'],
  [/:-&/g, '🤢'],
  [/\(y\)/gi, '👍'],
  [/\(n\)/gi, '👎'],
  [/\(ok\)/gi, '👌'],
  [/\(clap\)/gi, '👏'],
  [/\(wave\)/gi, '👋'],
  [/\(fire\)/gi, '🔥'],
  [/\(100\)/g, '💯'],
  [/\(star\)/gi, '⭐']
]

export function replaceEmoticons(text: string): string {
  return EMOTICONS.reduce((acc, [pattern, emoji]) => acc.replace(pattern, emoji), text)
}
